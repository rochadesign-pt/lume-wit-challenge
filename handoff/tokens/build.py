"""Build Lume design tokens from the Figma export.

    python3 handoff/tokens/build.py

Reads  handoff/tokens/figma-export.json   (source of truth, exported from Figma variables & styles)
Writes handoff/src/tokens.css              (CSS custom properties: Light + Dark, type, shadows)
       handoff/tokens/tokens.json          (W3C Design Tokens / DTCG format for Style Dictionary, Tokens Studio…)

Exploration-only tokens (the "warm/*" primitives and the "Explore · Warm v0.1" mode) are skipped:
they exist in Figma only to power the Explorations page.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = json.loads((ROOT / "figma-export.json").read_text())
CSS_OUT = ROOT.parent / "src" / "tokens.css"
DTCG_OUT = ROOT / "tokens.json"

WEIGHTS = {"Regular": 400, "Medium": 500, "SemiBold": 600, "Bold": 700}
FONT_STACK = '"Geist", system-ui, -apple-system, sans-serif'


def css_name(path: str) -> str:
    """'bg/accent-subtle' → '--lume-bg-accent-subtle'; 'Elevation/1 · Card' → '--lume-shadow-elevation-1-card'."""
    slug = re.sub(r"[^a-z0-9]+", "-", path.lower()).strip("-")
    return f"--lume-{slug}"


def is_exploration(name: str) -> bool:
    return name.startswith("warm/")


def rgba(hex_: str, alpha: float) -> str:
    h = hex_.lstrip("#")
    r, g, b = (int(h[i : i + 2], 16) for i in (0, 2, 4))
    return f"rgba({r}, {g}, {b}, {alpha:g})"


def shadow(layers) -> str:
    parts = []
    for kind, x, y, blur, spread, color, alpha in layers:
        inset = "inset " if kind == "inner" else ""
        parts.append(f"{inset}{x}px {y}px {blur}px {spread}px {rgba(color, alpha)}")
    return ", ".join(parts)


prims = {k: v for k, v in SRC["collections"]["Primitives"]["vars"].items() if not is_exploration(k)}
color = SRC["collections"]["Color"]
light_i, dark_i = color["modes"].index("Light"), color["modes"].index("Dark")
spacing = SRC["collections"]["Spacing"]["vars"]
radius = SRC["collections"]["Radius"]["vars"]

# ---------- CSS ----------
L = []
w = L.append
w("/* Lume design tokens. GENERATED by handoff/tokens/build.py from figma-export.json. Do not edit by hand.")
w("   Names mirror the Figma variables' WEB code syntax 1:1 (e.g. Figma bg/surface → var(--lume-bg-surface)). */")
w("")
w(":root {")
w("  /* Primitives (hidden in Figma: scopes = []). Never use directly in components. */")
for k, v in prims.items():
    w(f"  {css_name(k)}: {v};")
w("")
w("  /* Spacing & radius */")
for k, v in {**spacing, **radius}.items():
    w(f"  {css_name(k)}: {v}px;")
w("")
w("  /* Typography: one family, styles mirror Figma text styles. */")
w(f"  --lume-font-family: {FONT_STACK};")
for t in SRC["text"]:
    n = css_name("type/" + t["name"])
    w(f"  {n}: {WEIGHTS[t['style']]} {t['size']}px/{t['lineHeight']}px var(--lume-font-family);")
    w(f"  {n}-tracking: {t['letterSpacingPct'] / 100:g}em;")
w("")
w("  /* Elevation: layered, cool-tinted; the 1px spread layer is the 'ring' that replaces borders. */")
for e in SRC["effects"]:
    w(f"  {css_name('shadow/' + e['name'])}: {shadow(e['layers'])};")
w("")
w("  /* Semantic colour · Light */")
for k, modes in color["vars"].items():
    w(f"  {css_name(k)}: var({css_name(modes[light_i])});")
w("}")
w("")
dark = [f"{css_name(k)}: var({css_name(modes[dark_i])});" for k, modes in color["vars"].items()]
w("/* Semantic colour · Dark (system preference, unless the page forces light) */")
w("@media (prefers-color-scheme: dark) {")
w('  :root:not([data-theme="light"]) {')
for d in dark:
    w(f"    {d}")
w("  }")
w("}")
w('/* Semantic colour · Dark (forced: <html data-theme="dark">) */')
w(':root[data-theme="dark"] {')
for d in dark:
    w(f"  {d}")
w("}")
w("")
w("/* Text-style utility classes (same names as Figma text styles) */")
for t in SRC["text"]:
    n = css_name("type/" + t["name"])
    cls = n.replace("--lume-", ".lume-")
    extra = " text-transform: uppercase;" if t.get("textCase") == "UPPER" else ""
    tab = " font-variant-numeric: tabular-nums;" if t["name"].startswith("Numeric") else ""
    w(f"{cls} {{ font: var({n}); letter-spacing: var({n}-tracking);{extra}{tab} }}")
CSS_OUT.write_text("\n".join(L) + "\n")

# ---------- DTCG JSON ----------
def put(tree, path, token):
    node = tree
    parts = path.split("/")
    for p in parts[:-1]:
        node = node.setdefault(p, {})
    node[parts[-1]] = token

dtcg = {"primitive": {}, "color": {}, "space": {}, "radius": {}, "typography": {}, "shadow": {}}
for k, v in prims.items():
    put(dtcg["primitive"], k, {"$type": "color", "$value": v})
for k, modes in color["vars"].items():
    put(dtcg["color"], k, {
        "$type": "color",
        "$value": "{primitive." + modes[light_i].replace("/", ".") + "}",
        "$extensions": {"mode": {"dark": "{primitive." + modes[dark_i].replace("/", ".") + "}"}},
    })
for k, v in spacing.items():
    dtcg["space"][k.split("/")[1]] = {"$type": "dimension", "$value": f"{v}px"}
for k, v in radius.items():
    dtcg["radius"][k.split("/")[1]] = {"$type": "dimension", "$value": f"{v}px"}
for t in SRC["text"]:
    put(dtcg["typography"], t["name"], {"$type": "typography", "$value": {
        "fontFamily": t["family"], "fontWeight": WEIGHTS[t["style"]], "fontSize": f"{t['size']}px",
        "lineHeight": f"{t['lineHeight']}px", "letterSpacing": f"{t['letterSpacingPct'] / 100:g}em",
    }})
for e in SRC["effects"]:
    key = re.sub(r"\s*·\s*", "-", e["name"]).replace(" ", "-").lower()
    put(dtcg["shadow"], key, {"$type": "shadow", "$value": [
        {"color": rgba(c, a), "offsetX": f"{x}px", "offsetY": f"{y}px", "blur": f"{b}px", "spread": f"{s}px", "inset": kind == "inner"}
        for kind, x, y, b, s, c, a in e["layers"]
    ]})
DTCG_OUT.write_text(json.dumps(dtcg, indent=2, ensure_ascii=False) + "\n")

print(f"tokens.css  → {CSS_OUT.relative_to(ROOT.parent.parent)}  ({len(prims)} primitives, {len(color['vars'])} semantic, {len(SRC['text'])} type, {len(SRC['effects'])} shadows)")
print(f"tokens.json → {DTCG_OUT.relative_to(ROOT.parent.parent)}")
